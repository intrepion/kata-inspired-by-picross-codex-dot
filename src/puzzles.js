export const PUZZLES = drawings.map(([id, title, subtitle, color, rows]) => {
  const width = rows[0].length;
  if (rows.some(row => row.length !== width || /[^.#]/.test(row))) throw new Error(`Invalid original drawing: ${id}`);
  return { id, title, subtitle, color, width, height: rows.length, solution: rows.map(row => [...row].map(cell => cell === '#' ? 1 : 0)) };
});
